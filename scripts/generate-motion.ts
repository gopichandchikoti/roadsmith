// Writes src/themes/motion.css: the three named springs as CSS `linear()` easings, plus the shared enter keyframes. Run it
// again after changing a spring in src/utils/spring.ts.
import { writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { SPRINGS, springEasing, type SpringName } from '../src/utils/spring.ts'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const names = Object.keys(SPRINGS) as SpringName[]

const tokens = names
  .map((name) => {
    const { easing, durationMs } = springEasing(SPRINGS[name])
    const { response, dampingFraction } = SPRINGS[name]
    return `  /* ${name}: response ${response}s, damping fraction ${dampingFraction} */\n  --spring-${name}: ${easing};\n  --spring-${name}-time: ${durationMs}ms;`
  })
  .join('\n')

const fallbacks = names.map((name) => `    --spring-${name}: cubic-bezier(0.2, 0.8, 0.2, 1);`).join('\n')

const css = `/*
 * Spring motion. Generated by scripts/generate-motion.ts from src/utils/spring.ts: do not edit the numbers by hand.
 *
 * A change of screen or state moves on a damped spring, the way iOS does, instead of a fixed-time curve. Only transform
 * and opacity animate. Under reduced motion, travel and scale stop and only a short fade remains.
 */

:root {
${tokens}
}

@supports not (transition-timing-function: linear(0, 1)) {
  :root {
${fallbacks}
  }
}

@keyframes spring-rise-in { from { opacity: 0; transform: translateY(16px); } to { opacity: 1; transform: none; } }

@media (prefers-reduced-motion: reduce) {
  @keyframes spring-rise-in { from { opacity: 0; } to { opacity: 1; } }
}
`

writeFileSync(path.join(root, 'src/themes/motion.css'), css)
process.stdout.write(
  `motion.css written: ${names.map((name) => `${name} ${springEasing(SPRINGS[name]).durationMs}ms`).join(', ')}\n`,
)
